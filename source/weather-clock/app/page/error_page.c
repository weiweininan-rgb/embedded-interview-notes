// --- 1. C语言标准库引入 ---
#include <stdint.h>   // 引入标准整数类型库，允许使用 uint16_t（16位无符号整数）等精确的数据类型
#include <string.h>   // 引入字符串处理函数库，主要为了在下面使用 strlen() 函数来计算字符串长度

// --- 2. 工程自定义底层驱动与素材库引入 ---
#include "st7789.h"   // 引入 ST7789 LCD 屏幕驱动头文件，里面包含了画点、填色、写字等底层操作函数
#include "font.h"     // 引入字库头文件，里面存放了告诉单片机如何画出特定文字的点阵数据（如 font20_maple_bold）
#include "image.h"    // 引入图片头文件，里面存放了将图片转换成 C 语言数组的像素数据（如 img_error）

/**
 * @brief  错误页面显示函数
 * @param  msg: 指向一段字符串的指针，代表要在屏幕上显示的具体错误信息（例如 "WIFI Disconnected"）
 */
void error_page_display(const char *msg)
{
    // --- 第一步：定义背景颜色 ---
    // 使用 mkcolor(R, G, B) 宏将红绿蓝三原色转换为屏幕支持的 16 位颜色值。
    // R=0, G=0, B=0 代表纯黑色，赋值给一个不可修改的常量 color_bg。
    const uint16_t color_bg = mkcolor(0, 0, 0); 
    
    // --- 第二步：清空屏幕（刷背景色） ---
    // 调用屏幕填充函数。参数分别是：左上角X坐标(0), 左上角Y坐标(0), 
    // 右下角X坐标(屏幕最大宽度-1), 右下角Y坐标(屏幕最大高度-1), 填充颜色(黑色)。
    // 这一步相当于在画画前，把整个屏幕用黑色涂满，擦除之前显示的所有内容。
    st7789_fill_color(0, 0, ST7789_WIDTH - 1, ST7789_HEIGHT - 1, color_bg);
    
    // --- 第三步：绘制错误警告图标 ---
    // 在屏幕坐标 X=40, Y=37 的位置，调用画图函数，将 &img_error（警告图标的数组首地址）绘制到屏幕上。
    st7789_draw_image(40, 37, &img_error);
    
    // --- 第四步：计算文本居中显示的 X 坐标 ---
    // 定义变量 startx，用来存放最终决定写字的起始 X 坐标，默认从最左边(0)开始。
    uint16_t startx = 0; 
    
    // 计算即将显示的字符串在屏幕上总共会占用多少个像素的宽度：
    // 逻辑：字符总数(strlen) × 单个字体的设计大小(font20_maple_bold.size) ÷ 2
    // (除以2是因为英文字母是半角字符，宽度只有全角汉字设计尺寸的一半)
    int len = strlen(msg) * font20_maple_bold.size / 2;
    
    // 判断算出的文本总宽度是否小于屏幕的总宽度，如果小于，说明可以在一行内居中显示
    if (len < ST7789_WIDTH)
        // 居中坐标计算公式：(屏幕总宽度 - 文本占用总宽度 + 1) ÷ 2
        // 加 1 是为了在奇数像素宽度时做个四舍五入的微调，让视觉更居中
        startx = (ST7789_WIDTH - len + 1) / 2; 
        
    // --- 第五步：将错误信息文字渲染到屏幕上 ---
    // 调用写字函数。参数分别是：
    // startx: 刚刚算出来的水平居中 X 坐标
    // 245: 固定的 Y 坐标，代表文字显示在屏幕偏下方的位置
    // msg: 传入的错误信息字符串内容
    // mkcolor(255, 255, 0): 文字颜色设为纯黄色 (红+绿=黄)
    // color_bg: 文字背景色，设为刚才定义的纯黑色
    // &font20_maple_bold: 告诉屏幕使用 20号 Maple 粗体字库来画这些字
    st7789_write_string(startx, 245, msg, mkcolor(255, 255, 0), color_bg, &font20_maple_bold);
}
